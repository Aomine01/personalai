# Column width bounds
_MIN_COL_WIDTH: float = 10.0
_MAX_COL_WIDTH: float = 50.0


def _validate_table_data(data: dict) -> tuple[list[str], list[list[str]]]:  # type: ignore[type-arg]
    """
    Validate the JSON structure returned by Ollama for Excel generation.

    Expected shape:
        {"headers": ["Col A", "Col B", ...], "rows": [["v1", "v2"], ...]}

    Returns:
        (headers, rows) as plain string lists.

    Raises:
        ValueError: if structure is malformed, headers empty, or row lengths inconsistent.
    """
    if not isinstance(data, dict):
        raise ValueError("Expected a JSON object, got non-dict")

    headers = data.get("headers")
    rows = data.get("rows")

    if not headers or not isinstance(headers, list):
        raise ValueError("'headers' key missing or empty")
    if not rows or not isinstance(rows, list):
        raise ValueError("'rows' key missing or empty")

    # Coerce headers to str
    headers = [str(h).strip() for h in headers]
    if not all(headers):
        raise ValueError("One or more headers are empty strings")

    n_cols = len(headers)
    validated_rows: list[list[str]] = []
    for i, row in enumerate(rows):
        if not isinstance(row, list):
            raise ValueError(f"Row {i} is not a list")
        if len(row) != n_cols:
            raise ValueError(
                f"Row {i} has {len(row)} cells but headers define {n_cols} columns"
            )
        validated_rows.append([str(c) for c in row])

    return headers, validated_rows


def generate_excel(
    headers: list[str],
    rows: list[list[str]],
    title: str = "AI Generated Report",
    sheet_name: str = "Data",
) -> str:
    """
    Build a formatted .xlsx from *headers* + *rows* and return the local path.

    Design:
      - Bold blue header row with white text
      - Alternating light-grey / white row shading
      - Auto-filter on the header row
      - Auto-sized column widths (capped at MAX_COL_WIDTH)

    Raises:
        ImportError: if openpyxl is not installed.
        Exception:   on any rendering error.
    """
    try:
        import openpyxl  # noqa: PLC0415
        from openpyxl.styles import (  # noqa: PLC0415
            Alignment, Font, PatternFill, Border, Side,
        )
        from openpyxl.utils import get_column_letter  # noqa: PLC0415
    except ImportError as exc:
        raise ImportError("openpyxl is required. Run: pip install openpyxl") from exc

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = sheet_name[:31]   # Excel max sheet name length = 31

    # ── Styles ────────────────────────────────────────────────────────────────
    BLUE = "2962FF"
    LIGHT_GREY = "F2F2F2"
    BORDER_GREY = "CCCCCC"

    header_font   = Font(bold=True, color="FFFFFF", size=11)
    header_fill   = PatternFill("solid", fgColor=BLUE)
    data_font     = Font(size=10)
    alt_fill      = PatternFill("solid", fgColor=LIGHT_GREY)
    thin_border   = Border(
        bottom=Side(style="thin", color=BORDER_GREY),
        right=Side(style="thin", color=BORDER_GREY),
    )
    center_align  = Alignment(horizontal="center", vertical="center", wrap_text=True)
    left_align    = Alignment(horizontal="left", vertical="center", wrap_text=True)

    # ── Title row ─────────────────────────────────────────────────────────────
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    title_cell = ws.cell(row=1, column=1, value=title)
    title_cell.font = Font(bold=True, size=13, color=BLUE)
    title_cell.alignment = center_align
    ws.row_dimensions[1].height = 28

    # ── Header row ────────────────────────────────────────────────────────────
    for col_idx, header in enumerate(headers, start=1):
        cell = ws.cell(row=2, column=col_idx, value=header)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = center_align
        cell.border = thin_border
    ws.row_dimensions[2].height = 22

    # ── Data rows ─────────────────────────────────────────────────────────────
    for row_idx, row in enumerate(rows, start=3):
        fill = alt_fill if (row_idx % 2 == 1) else PatternFill()
        for col_idx, value in enumerate(row, start=1):
            cell = ws.cell(row=row_idx, column=col_idx, value=value)
            cell.font = data_font
            cell.fill = fill
            cell.alignment = left_align
            cell.border = thin_border
        ws.row_dimensions[row_idx].height = 18

    # ── Auto-filter on header row ─────────────────────────────────────────────
    ws.auto_filter.ref = ws.dimensions   # covers header + data

    # ── Auto column widths ────────────────────────────────────────────────────
    for col_idx in range(1, len(headers) + 1):
        col_letter = get_column_letter(col_idx)
        max_len = 0
        for row_cells in ws.iter_rows(min_col=col_idx, max_col=col_idx):
            for cell in row_cells:
                try:
                    cell_len = len(str(cell.value)) if cell.value else 0
                    max_len = max(max_len, cell_len)
                except Exception:
                    pass
        width = max(min(max_len + 4, _MAX_COL_WIDTH), _MIN_COL_WIDTH)
        ws.column_dimensions[col_letter].width = width

    # ── Freeze panes below header ─────────────────────────────────────────────
    ws.freeze_panes = "A3"

    out_path = _tmp_path("xlsx")
    wb.save(str(out_path))
    logger.info(
        "XLSX written to %s (%d rows × %d cols)",
        out_path, len(rows), len(headers),
    )
    return str(out_path)
