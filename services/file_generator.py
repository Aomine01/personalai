# Word Document Generation (python-docx)
# ---------------------------------------------------------------------------

def generate_docx(
    history: list[dict[str, str]],
    title: str = "Conversation Report",
) -> str:
    """
    Build a formatted .docx from *history* and return the local file path.

    Raises:
        ImportError: if python-docx is not installed.
        Exception:   on any rendering error.
    """
    try:
        from docx import Document  # noqa: PLC0415
        from docx.shared import Pt, RGBColor, Inches  # noqa: PLC0415
        from docx.enum.text import WD_ALIGN_PARAGRAPH  # noqa: PLC0415
        from docx.oxml.ns import qn  # noqa: PLC0415
        from docx.oxml import OxmlElement  # noqa: PLC0415
    except ImportError as exc:
        raise ImportError(
            "python-docx is required. Install with: pip install python-docx"
        ) from exc

    def set_cell_bg(cell, hex_color: str) -> None:
        """Apply background shading to a table cell."""
        tc = cell._tc
        tcPr = tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"), hex_color)
        tcPr.append(shd)

    doc = Document()

    # ---- Page margins ----
    for section in doc.sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1.2)
        section.right_margin = Inches(1.2)

    # ---- Title ----
    title_para = doc.add_heading(title, level=0)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in title_para.runs:
        run.font.color.rgb = RGBColor(41, 98, 255)
        run.font.size = Pt(22)

    # ---- Metadata subtitle ----
    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = sub.add_run(
        f"Generated by AI Agent  ·  {datetime.now().strftime('%B %d, %Y at %H:%M')}"
    )
    run.font.color.rgb = RGBColor(130, 130, 130)
    run.font.size = Pt(9)
    run.italic = True

    doc.add_paragraph()  # spacer

    turns = _format_history(history)
    if not turns:
        p = doc.add_paragraph()
        run = p.add_run("No conversation history available.")
        run.italic = True
        run.font.color.rgb = RGBColor(130, 130, 130)
    else:
        for label, content in turns:
            is_user = label == "You"

            # One-row, two-column table: [SPEAKER | MESSAGE]
            table = doc.add_table(rows=1, cols=2)
            table.style = "Table Grid"
            table.columns[0].width = Inches(1.0)
            table.columns[1].width = Inches(4.8)

            row = table.rows[0]

            # Speaker cell
            speaker_cell = row.cells[0]
            set_cell_bg(speaker_cell, "2962FF" if is_user else "505050")
            sp = speaker_cell.paragraphs[0]
            sp.alignment = WD_ALIGN_PARAGRAPH.CENTER
            sr = sp.add_run(label)
            sr.font.bold = True
            sr.font.color.rgb = RGBColor(255, 255, 255)
            sr.font.size = Pt(9)

            # Message cell
            msg_cell = row.cells[1]
            set_cell_bg(msg_cell, "F5F5F5")
            mp = msg_cell.paragraphs[0]
            mr = mp.add_run(content)
            mr.font.size = Pt(10)
            mr.font.color.rgb = RGBColor(60, 60, 60)

            doc.add_paragraph()  # spacer between turns

    out_path = _tmp_path("docx")
    doc.save(str(out_path))
    logger.info("DOCX written to %s (%d turns)", out_path, len(turns))
    return str(out_path)


