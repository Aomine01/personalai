"""
services/file_generator.py — PDF and Word document generation.

PDF:   uses fpdf2   (pip install fpdf2)
DOCX:  uses python-docx (pip install python-docx)

Both functions accept the user's conversation history and write a nicely
formatted document to a temp file, returning the absolute path.
"""
from __future__ import annotations

import logging
import uuid
from datetime import datetime
from pathlib import Path
from typing import Final

from config import settings

logger = logging.getLogger(__name__)

# Colours used across both generators (RGB tuples)
_BRAND_BLUE: Final = (41, 98, 255)
_LIGHT_GREY: Final = (245, 245, 245)
_DARK_GREY: Final = (60, 60, 60)
_MID_GREY: Final = (130, 130, 130)
_WHITE: Final = (255, 255, 255)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _tmp_path(extension: str) -> Path:
    name = f"aiagent_{uuid.uuid4().hex[:10]}.{extension}"
    return Path(settings.TMP_DIR) / name


def _format_history(history: list[dict[str, str]]) -> list[tuple[str, str]]:
    """Convert raw history list → list of (speaker_label, message) tuples."""
    out: list[tuple[str, str]] = []
    for turn in history:
        role = turn.get("role", "user")
        content = turn.get("content", "").strip()
        if not content:
            continue
        label = "You" if role == "user" else "Assistant"
        out.append((label, content))
    return out


# ---------------------------------------------------------------------------
# PDF Generation (fpdf2)
# ---------------------------------------------------------------------------

def generate_pdf(
    history: list[dict[str, str]],
    title: str = "Conversation Summary",
) -> str:
    """
    Build a formatted PDF from *history* and return the local file path.

    Raises:
        ImportError: if fpdf2 is not installed.
        Exception:   on any rendering error.
    """
    try:
        from fpdf import FPDF, XPos, YPos  # noqa: PLC0415
    except ImportError as exc:
        raise ImportError(
            "fpdf2 is required. Install with: pip install fpdf2"
        ) from exc

    class StyledPDF(FPDF):
        def header(self) -> None:  # type: ignore[override]
            # Blue banner
            self.set_fill_color(*_BRAND_BLUE)
            self.rect(0, 0, self.w, 22, style="F")
            self.set_font("Helvetica", "B", 14)
            self.set_text_color(*_WHITE)
            self.set_y(5)
            self.cell(0, 12, title, align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            self.set_text_color(*_DARK_GREY)
            self.ln(6)

        def footer(self) -> None:  # type: ignore[override]
            self.set_y(-15)
            self.set_font("Helvetica", "I", 8)
            self.set_text_color(*_MID_GREY)
            ts = datetime.now().strftime("%Y-%m-%d %H:%M")
            self.cell(0, 10, f"Generated by AI Agent  ·  {ts}  ·  Page {self.page_no()}", align="C")

    pdf = StyledPDF(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.set_margins(left=18, top=28, right=18)
    pdf.add_page()

    turns = _format_history(history)
    if not turns:
        pdf.set_font("Helvetica", "I", 11)
        pdf.set_text_color(*_MID_GREY)
        pdf.cell(0, 10, "No conversation history available.", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    else:
        for label, content in turns:
            is_user = label == "You"

            # Speaker badge
            pdf.set_font("Helvetica", "B", 9)
            badge_color = _BRAND_BLUE if is_user else (80, 80, 80)
            pdf.set_fill_color(*badge_color)
            pdf.set_text_color(*_WHITE)
            pdf.cell(18, 6, label, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            # Message bubble background
            pdf.set_fill_color(*_LIGHT_GREY)
            pdf.set_text_color(*_DARK_GREY)
            pdf.set_font("Helvetica", size=10)
            pdf.multi_cell(
                0,
                6,
                content,
                fill=True,
                new_x=XPos.LMARGIN,
                new_y=YPos.NEXT,
            )
            pdf.ln(3)

    out_path = _tmp_path("pdf")
    pdf.output(str(out_path))
    logger.info("PDF written to %s (%d turns)", out_path, len(turns))
    return str(out_path)


